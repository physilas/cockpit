#!/usr/bin/env python3
"""
build.py  –  Bündelt alle Python-Backend-Dateien in eine einzige JS-Datei
             (frontend/web/js/engine-src.js), die von app.js direkt geladen
             wird. So braucht die Web-Seite keine ../../-Pfade mehr und
             GitHub Pages kann keine einzelne .py-Datei auslassen oder
             verweigern.

Ausführen (aus dem Repo-Root):
    python3 build.py
"""
import hashlib
import html
import json
from pathlib import Path

ROOT = Path(__file__).parent

PYTHON_DATEIEN = [
    "backend/__init__.py",
    "backend/regeln.py",
    "backend/ui_schema.py",
    "backend/wuerfel.py",
    "backend/wuerfelfeld.py",
    "backend/cockpit.py",
    "backend/landung.py",
    "backend/katalog.py",
    "backend/zusatzregeln.py",
    "backend/spielplan.py",
    "backend/bridge.py",
    "ai/__init__.py",
    "ai/actions.py",
    "ai/observation.py",
    "ai/environment.py",
    "ai/public_rules.py",
    "ai/tactics.py",
    "ai/browser_bridge.py",
]

UI_SCHEMA = "backend/ui_schema.json"


def build():
    sources = {}

    for rel in PYTHON_DATEIEN:
        pfad = ROOT / rel
        text = pfad.read_text(encoding="utf-8")
        sources[rel] = text
        print(f"  {rel}: {len(text):>6} Zeichen")

    schema_path = ROOT / UI_SCHEMA
    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    sources[UI_SCHEMA] = json.dumps(schema, ensure_ascii=False, indent=2) + "\n"
    sources["backend/landekatalog.json"] = (ROOT / "backend/landekatalog.json").read_text(encoding="utf-8")
    sources["backend/bildnachweise.json"] = (ROOT / "backend/bildnachweise.json").read_text(encoding="utf-8")
    print(f"  {UI_SCHEMA}: {len(sources[UI_SCHEMA]):>6} Zeichen")

    # Jede YAML-Datei unter backend/landungen/ wird automatisch mit
    # eingebündelt - neue Flughäfen (z.B. LHR.yaml) tauchen so ohne
    # Anpassung an dieser Datei sowohl in der Engine als auch in der
    # Frontend-Auswahl (backend/landung.py: flughafen_liste()) auf.
    landungen_dir = ROOT / "backend" / "landungen"
    for yaml_pfad in sorted(landungen_dir.glob("*.yaml")):
        rel = f"backend/landungen/{yaml_pfad.name}"
        text = yaml_pfad.read_text(encoding="utf-8")
        sources[rel] = text
        print(f"  {rel}: {len(text):>6} Zeichen")

    out = ROOT / "frontend" / "web" / "js" / "engine-src.js"
    content = (
        "/* AUTO-GENERATED by build.py - nicht manuell bearbeiten */\n"
        "/* Regenerieren: python3 build.py  (aus dem Repo-Root) */\n\n"
        "const ENGINE_SRC = "
        + json.dumps(sources, ensure_ascii=False, indent=2)
        + ";\n"
    )
    out.write_text(content, encoding="utf-8")
    print(f"\nFertig: {out.relative_to(ROOT)}  ({out.stat().st_size // 1024} KB)")

    schema_out = ROOT / "frontend" / "web" / "js" / "game-schema.js"
    schema_out.write_text(
        "/* AUTO-GENERATED by build.py - nicht manuell bearbeiten */\n"
        "window.COCKPIT_SCHEMA = " + json.dumps(schema, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    from backend.katalog import landekatalog
    catalog_out = ROOT / "frontend/web/js/landing-catalog.js"
    katalog = landekatalog()
    catalog_out.write_text(
        "/* AUTO-GENERATED by build.py */\nwindow.LANDING_CATALOG = "
        + json.dumps(katalog, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    esc = html.escape
    credit_items = []
    for code, photo in sorted(katalog["photos"].items()):
        credit_items.append(
            f'<article id="{esc(code)}" class="photo-credit-item">'
            f'<img src="{esc(photo["path"])}" alt="{esc(photo["alt"])}" loading="lazy" '
            f'width="{photo["width"]}" height="{photo["height"]}">'
            f'<div><h2>{esc(code)} · {esc(photo["location"])}</h2>'
            f'<p class="photo-credit-title">{esc(photo["title"])}</p>'
            f'<p>Foto: <strong>{esc(photo["author"])}</strong></p>'
            f'<p><a href="{esc(photo["source_url"])}" target="_blank" rel="noopener">Quelle auf Wikimedia Commons ↗</a>'
            f' · <a href="{esc(photo["license_url"])}" target="_blank" rel="noopener">{esc(photo["license"])}</a></p>'
            f'<p>{esc(photo["changes"])} Die verwendete Bildfassung steht unter {esc(photo["derivative_license"])}.</p>'
            f'<p class="photo-credit-date">Lizenzangaben geprüft am {esc(photo["verified_on"])}.</p></div></article>'
        )
    credits_out = ROOT / "frontend/web/bildnachweise.html"
    credits_out.write_text(
        '<!doctype html>\n<html lang="de"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        '<title>Bildnachweise · Fly Team</title><link rel="stylesheet" href="css/style.css">'
        '<link rel="stylesheet" href="css/landings.css"></head><body class="photo-credits-page">'
        '<div class="landing-shell"><nav class="landing-nav"><a class="landing-back" href="index.html?view=landings">← Landungen</a>'
        '<span>✈ FLY TEAM</span></nav><h1>Bildnachweise</h1>'
        '<p class="photo-credits-intro">Die Stadtpanoramen stammen von Wikimedia Commons. Hier findest du für jedes Foto '
        'die Urheber, die Quelle und die konkret verwendete Lizenz. Die Bildfassungen behalten die jeweils angegebene Lizenz.</p>'
        + "\n".join(credit_items) + '</div></body></html>\n', encoding="utf-8",
    )

    # The service worker is cache-first, so its cache key must also change for
    # HTML, CSS and browser JavaScript edits—not only when the Python engine
    # bundle changes.
    cache_inputs = [
        content,
        schema_out.read_text(encoding="utf-8"),
        catalog_out.read_text(encoding="utf-8"),
        credits_out.read_text(encoding="utf-8"),
        *[
            (ROOT / rel).read_text(encoding="utf-8")
            for rel in (
                "frontend/web/index.html",
                "frontend/web/multiplayer.html",
                "frontend/web/manifest.json",
                "frontend/web/css/style.css",
                "frontend/web/css/landings.css",
                "frontend/web/css/modules.css",
                "frontend/web/css/reroll.css",
                "frontend/web/css/singleplayer.css",
                "frontend/web/js/modules.js",
                "frontend/web/js/reroll.js",
                "frontend/web/js/ai-models.js",
                "frontend/web/js/ai-policy.js",
                "frontend/web/js/cloud-config.js",
                "frontend/web/js/learning-cloud.js",
                "frontend/web/js/singleplayer.js",
                "frontend/web/js/landings.js",
                "frontend/web/js/app.js",
                "frontend/web/js/traffic.js",
                "frontend/web/js/multiplayer.js",
                "frontend/web/sw.js",
            )
        ],
    ]
    cache_inputs.extend(p.read_bytes().hex() for p in sorted((ROOT / "frontend/web/assets/landings").glob("*.webp")))
    digest = hashlib.sha256("".join(cache_inputs).encode("utf-8")).hexdigest()[:12]
    info_out = ROOT / "frontend" / "web" / "js" / "build-info.js"
    info_out.write_text(
        "/* AUTO-GENERATED by build.py - cache version for the service worker */\n"
        f'const COCKPIT_BUILD_VERSION = "{digest}";\n',
        encoding="utf-8",
    )
    print(f"Fertig: {schema_out.relative_to(ROOT)}")
    print(f"Fertig: {info_out.relative_to(ROOT)}")


if __name__ == "__main__":
    build()
