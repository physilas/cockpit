"""Build the app plus a measured, integrity-checked offline inventory.

Keep build.py unchanged: released AI strategy fingerprints include its bytes.
Run `make build` after changing app files, model exports or vendored runtime.
"""
import hashlib
import json
from pathlib import Path

import build

WEB = Path(__file__).parent / "frontend/web"
RUNTIME = "vendor/pyodide/0.26.1/"
# Shared by the worker and the size display; no hidden training checkpoints.
SHELL = [
    "index.html", "manifest.json", "bildnachweise.html", "multiplayer.html",
    *[f"css/{name}.css" for name in ("style", "landings", "modules", "reroll",
        "singleplayer", "game-dialogs", "game-experience")],
    *[f"js/{name}.js" for name in ("modules", "reroll", "ai-models", "ai-policy",
        "cloud-config", "learning-cloud", "singleplayer", "game-dialogs",
        "game-experience", "landing-catalog", "landings", "engine-src",
        "game-schema", "traffic", "build-info", "app", "multiplayer", "offline", "feedback-actions", "cockpit-controls", "cockpit-layout", "multiplayer-lobby", "app-updates")],
    *[f"icons/icon-fly-team-{size}.png" for size in (180, 192, 512)],
    *[f"assets/landings/{code}-city.webp" for code in
      ("YUL", "LHR", "HND", "OSL", "ATL", "PRG", "GIG", "TGU", "KEF", "KUL", "PBH", "MUC", "FRA")],
    RUNTIME + "pyodide.js",
]


def inventory():
    catalog = json.loads((WEB / "js/ai-models.js").read_text().split(" = ", 1)[1].rstrip(";\n"))
    models = [m for m in catalog["models"] if not m.get("ui_hidden")
              and (m.get("quality", {}).get("approved") or m.get("preview", {}).get("enabled"))]
    lock = json.loads((WEB / RUNTIME / "pyodide-lock.json").read_text())
    yaml = lock["packages"]["pyyaml"]
    assert not yaml["depends"], "Add runtime dependencies to the offline inventory"
    assert hashlib.sha256((WEB / RUNTIME / yaml["file_name"]).read_bytes()).hexdigest() == yaml["sha256"]
    paths = [RUNTIME + name for name in ("pyodide.asm.js", "pyodide.asm.wasm",
             "python_stdlib.zip", "pyodide-lock.json", yaml["file_name"])]
    paths += sorted({m["url"] for m in models})
    def record(path):
        data = (WEB / path).read_bytes()
        return {"url": path, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    result = {"cache": "cockpit-ai-assets-v1", "shell": [record(p) for p in SHELL],
              "assets": [record(p) for p in paths],
              "models": [{"name": m["name"], "url": m["url"], "bytes": (WEB / m["url"]).stat().st_size} for m in models]}
    result["bytes"] = sum(r["bytes"] for r in result["shell"] + result["assets"])
    result["version"] = hashlib.sha256(json.dumps(result, sort_keys=True).encode()).hexdigest()[:16]
    return result


def build_pwa():
    original = list(build.PYTHON_DATEIEN)
    build.PYTHON_DATEIEN.append("play_options.py")
    try:
        build.build()
    finally:
        build.PYTHON_DATEIEN[:] = original
    result = inventory()
    (WEB / "js/offline-assets.js").write_text(
        "/* Generated by build_pwa.py. */\nconst COCKPIT_OFFLINE_ASSETS = "
        + json.dumps(result, separators=(",", ":")) + ";\n")
    print(f"Offline pack: {result['bytes'] / 1e6:.2f} MB + inventory; {len(result['models'])} crews")


if __name__ == "__main__":
    build_pwa()
