"""Export all compatible local checkpoints for static, browser-only inference.

Run `python -m ai.export_browser` after training. The normal frontend build
does not require torch; it preserves the last exported catalog.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path

from .actions import ACTION_MASK_VERSION
from .checkpoints import load_checkpoint, schema, model_schema

ROOT = Path(__file__).resolve().parents[1]


def _layers(model):
    layers=[]
    for layer in [*model.encoder,model.actor]:
        if hasattr(layer,'weight'):
            layers.append({'input':layer.in_features,'output':layer.out_features,
                'weight':base64.b64encode(layer.weight.detach().cpu().numpy().astype('<f4').tobytes()).decode(),
                'bias':base64.b64encode(layer.bias.detach().cpu().numpy().astype('<f4').tobytes()).decode()})
    return layers



def _model_data(model):
    current=model_schema(model)
    if model.config.get('kind') in ('residual','guided_residual'):
        return {'format':4 if model.config['kind']=='guided_residual' else 3,
                **({'guide_margin':model.guide_margin} if model.config['kind']=='guided_residual' else {}),
                'schema':current,'model_config':model.config,
                'source':_model_data(model.source),
                'residual':{'format':1,'schema':current,'layers':_layers(model.residual)}}
    if hasattr(model,'roles'):
        return {'format':2,'schema':current,'roles':{r:_layers(m) for r,m in model.roles.items()},'model_config':model.config}
    return {'format':1,'schema':current,'layers':_layers(model),'model_config':model.config}

def export_models(runs_dir, output_dir, *, checkpoints=None, merge=False):
    output_dir = Path(output_dir)
    catalog_path = output_dir / 'js' / 'ai-models.js'
    previous = None
    if merge and catalog_path.exists():
        previous = json.loads(catalog_path.read_text().split(' = ', 1)[1].strip().rstrip(';'))
        if previous['schema'] != schema():
            raise ValueError('Existing browser catalog uses a different model schema.')
    assets = output_dir / "models"
    assets.mkdir(parents=True, exist_ok=True)
    models, skipped = [], []
    for path in sorted(checkpoints if checkpoints is not None else Path(runs_dir).rglob("*.pt")):
        path = Path(path)
        if path.stem not in ("best", "latest"):
            continue
        try:
            model, payload = load_checkpoint(path)
            config = payload.get("train_config", {})
            current_schema = model_schema(model)
            data = _model_data(model)
            raw = json.dumps(data, separators=(",", ":")).encode()
            fingerprint = hashlib.sha256(raw).hexdigest()
            asset = assets / f"{fingerprint}.json"
            if not asset.exists():
                asset.write_bytes(raw)
            name = path.relative_to(runs_dir).as_posix()
            models.append({"id": name, "run": str(path.parent.relative_to(runs_dir)),
                           "checkpoint": path.stem, "steps": payload.get("total_steps", 0),
                           "airport": config.get("airport", "MUC"), "max_steps": config.get("max_steps", 256),
                           "task_weight": config.get("task_weight", 0),
                           'assistance_version': config.get('assistance_version', 0),
                           'name': config.get('display_name'), 'recommended': config.get('recommended', False),
                           'supported_airports': config.get('supported_airports', [config.get('airport', 'MUC')]),
                           'quality': config.get('quality'),
                           "trained_action_mask_version": config.get("action_mask_version", 1),
                           "schema": current_schema, "fingerprint": fingerprint, "url": f"models/{asset.name}"})
        except (ValueError, KeyError, RuntimeError, OSError) as error:
            skipped.append({"checkpoint": str(path.relative_to(runs_dir)), "reason": str(error)})
    if previous:
        new_ids = {m['id'] for m in models}
        old = [m for m in previous['models'] if m['id'] not in new_ids]
        if any(m.get('recommended') for m in models):
            old = [{**m, 'recommended': False} for m in old]
        models = models + old
    catalog = {"format": 1, "schema": schema(), "action_mask_version": ACTION_MASK_VERSION,
               "models": models, "skipped": skipped}
    target = output_dir / "js" / "ai-models.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(".tmp")
    temporary.write_text("/* AUTO-GENERATED by python -m ai.export_browser */\nwindow.COCKPIT_AI_CATALOG = "
                         + json.dumps(catalog, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    temporary.replace(target)
    return catalog


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs-dir", type=Path, default=ROOT / "runs")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "frontend/web")
    args = parser.parse_args()
    catalog = export_models(args.runs_dir, args.output_dir)
    print(f"{len(catalog['models'])} Modelle exportiert; {len(catalog['skipped'])} inkompatible Checkpoints übersprungen.")
    for skipped in catalog["skipped"]:
        print(f"  {skipped['checkpoint']}: {skipped['reason']}")


if __name__ == "__main__":
    main()
